import gradio as gr
import cv2
import numpy as np
import tensorflow as tf # Import tensorflow to access Keras components
from tensorflow.keras.models import load_model

# ==============================
# تحميل الموديل
# ==============================
# Define custom objects to help load the model, especially for metrics/losses.
# The error mentioned 'keras.metrics.mse', but 'mse' was used as a loss in compilation.
# We need to explicitly map it as a loss to resolve the deserialization issue.
custom_objects = {
    'mse': tf.keras.losses.MeanSquaredError, # Map 'mse' as a LOSS, as it was used in model.compile
    'mae': tf.keras.metrics.MeanAbsoluteError, # Map 'mae' as a METRIC, as it was used in model.compile
    'binary_crossentropy': tf.keras.losses.BinaryCrossentropy # Map 'binary_crossentropy' as a LOSS
}

model = load_model("age_gender_model.h5", custom_objects=custom_objects)

# ==============================
# دالة التنبؤ
# ==============================
def predict(img):

    # تحويل الصورة
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    img = cv2.resize(img, (128,128)) / 255.0
    img = np.expand_dims(img, axis=0)

    # prediction
    gender_pred, age_pred = model.predict(img)

    gender = "Female" if gender_pred[0][0] > 0.5 else "Male"
    age = int(age_pred[0][0] * 100)

    return gender, age

# ==============================
# واجهة التطبيق
# ==============================
interface = gr.Interface(
    fn=predict,
    inputs=gr.Image(),
    outputs=["text", "text"],
    title="Age & Gender Prediction",
    description="Upload an image and get Age + Gender prediction"
)

interface.launch()
import cv2
import numpy as np

images = []
ages = []
genders = []

path = "crop_part1"

for img_name in os.listdir(path):
    try:
        age = int(img_name.split("_")[0])
        gender = int(img_name.split("_")[1])

        img_path = os.path.join(path, img_name)
        img = cv2.imread(img_path)

        # 🔴 MODIFIED (مهم جدًا: تحويل لـ RGB)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        img = cv2.resize(img, (128,128))

        images.append(img)
        ages.append(age)
        genders.append(gender)

    except:
        continue


# 🔴 MODIFIED (تثبيت النوع + normalization)
images = np.array(images, dtype=np.float32) / 255.0
ages = np.array(ages, dtype=np.float32) / 100.0
genders = np.array(genders, dtype=np.float32)

print("Data Loaded:", images.shape)

from sklearn.model_selection import train_test_split

X_train, X_test, y_gender_train, y_gender_test, y_age_train, y_age_test = train_test_split(
    images, genders, ages, test_size=0.2, random_state=42
)

from tensorflow.keras import layers, models

input_layer = layers.Input(shape=(128,128,3))

x = layers.Conv2D(32, (3,3), activation='relu')(input_layer)
x = layers.MaxPooling2D(2,2)(x)

x = layers.Conv2D(64, (3,3), activation='relu')(x)
x = layers.MaxPooling2D(2,2)(x)

x = layers.Flatten()(x)

# Gender Output
gender_output = layers.Dense(1, activation='sigmoid', name='gender')(x)

# Age Output
age_output = layers.Dense(1, activation='linear', name='age')(x)

model = models.Model(inputs=input_layer, outputs=[gender_output, age_output])

model.compile(
    optimizer='adam',
    loss={
        'gender': 'binary_crossentropy',
        'age': 'mse'
    },
    metrics={
        'gender': 'accuracy',
        'age': 'mae'
    }
)

model.summary()


# ==============================
# 5) تدريب الموديل
# ==============================

history = model.fit(
    X_train,
    {'gender': y_gender_train, 'age': y_age_train},
    epochs=10,
    validation_data=(X_test, {'gender': y_gender_test, 'age': y_age_test})
)

# ==============================
# 6) تقييم الموديل
# ==============================

model.evaluate(
    X_test,
    {'gender': y_gender_test, 'age': y_age_test}
)

